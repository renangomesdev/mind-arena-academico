package com.mindarena;

import com.mindarena.repository.GameSessionRepository;
import com.mindarena.repository.PlayerRepository;
import com.mindarena.service.GameService;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import java.sql.DriverManager;
import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@ActiveProfiles("test")
class LegacySchemaIntegrationTest {
    @Autowired GameService service;
    @Autowired GameSessionRepository games;
    @Autowired PlayerRepository players;
    @Autowired PlatformTransactionManager transactions;

    @DynamicPropertySource
    static void legacySchema(DynamicPropertyRegistry properties) throws Exception {
        String url = "jdbc:h2:mem:legacy-schema;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
        properties.add("spring.datasource.url", () -> url);
        properties.add("spring.jpa.hibernate.ddl-auto", () -> "update");
        try (var connection = DriverManager.getConnection(url, "sa", ""); var sql = connection.createStatement()) {
            sql.execute("create table quiz (id bigint generated by default as identity (start with 1001) primary key, title varchar(255), description varchar(500))");
            sql.execute("insert into quiz values (1000, 'Quiz anterior', 'Dados preservados')");
            sql.execute("create table game_session (id bigint generated by default as identity (start with 1001) primary key, code varchar(255) not null unique, quiz_id bigint not null, status varchar(255) check (status in ('WAITING','STARTING','QUESTION_ACTIVE','QUESTION_ENDED','FINISHED')), powers_enabled boolean, current_question_index integer, host_token varchar(255), current_question_start_time bigint)");
            sql.execute("insert into game_session values (1000, 'LG1234', 1000, 'WAITING', false, -1, '11111111-1111-1111-1111-111111111111', null)");
            sql.execute("create table player (id bigint generated by default as identity (start with 1001) primary key, nickname varchar(255), avatar varchar(255), score integer, streak integer, used_blind boolean, used_hint boolean, blind_until bigint, hint_question_id bigint, player_token varchar(255), game_session_id bigint)");
            sql.execute("insert into player values (1000, 'Aluno anterior', 'centurion', 777, 1, false, false, null, null, '22222222-2222-2222-2222-222222222222', 1000)");
        }
    }

    @Test void updatesOldSchemaWithoutChangingScoresTokensOrStatusConstraint() {
        var legacy = games.findByCode("LG1234").orElseThrow();
        assertNotNull(legacy.getCreatedAt());
        assertFalse(legacy.isJoinLocked());
        assertFalse(legacy.isExpired());
        assertFalse(players.findById(1000L).orElseThrow().isRemoved());
        service.verifyHostToken("LG1234", "11111111-1111-1111-1111-111111111111");
        service.verifyPlayerToken(1000L, "22222222-2222-2222-2222-222222222222");
        assertEquals(777, players.findById(1000L).orElseThrow().getScore());
        assertEquals("centurion", players.findById(1000L).orElseThrow().getAvatar());
        new TransactionTemplate(transactions).executeWithoutResult(status ->
            org.springframework.test.util.ReflectionTestUtils.setField(games.findByCodeForUpdate("LG1234").orElseThrow(), "createdAt", java.time.Instant.now().minusSeconds(13 * 3600L)));
        service.expireOldGames();
        assertTrue(games.findByCode("LG1234").orElseThrow().isExpired());
        assertEquals(777, players.findById(1000L).orElseThrow().getScore());
    }
}
